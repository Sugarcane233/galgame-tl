"""Unity 运行时汉化（BepInEx + XUnity.AutoTranslator）。

为什么需要这条路
----------------
Unity 的 MonoBehaviour 没有 TypeTree（打包时被剥掉），对象的**长度由
Assembly-CSharp.dll 里的类布局决定**。直接把字符串改长，Unity 启动时会
报 `A scripted object has a different serialization layout when loading.
(Read 300 bytes but expected 316 bytes)` 并丢弃整个对象 —— 场景加载失败，
表现为**闪过 logo 后黑屏**。

实测 1.2G 的 Together Again：全量回填后 1869 个对象变长，其中 1937 个字段
后面还有别的数据（不在对象末尾），硬改必崩。硬凑成等长又得截断 950 条译文
（中位超 8 字节，最长超 155 字节），译文尾巴全丢。

于是改走运行时替换：**一个字节都不碰资源文件**，让 XUnity 在游戏进程内
钩住 `UnityEngine.UI.Text.set_text` / `TMPro.TMP_Text.SetText`，用我们生成
的离线词典替换文本。代价是超长的译文能正常显示（不受原字段长度限制）。

实测结论（Together Again 1.0.3，Unity 2018.4.22f1 Mono）
------------------------------------------------------
* `serialization layout` 警告 0 条，`corrupted` 0 条；
* 136 个资源文件与原始快照逐字节一致；
* 主菜单的 NSFW 免责声明被替换成中文，日志确认
  `Setting text on 'UnityEngine.UI.Text' to 'NSFW免责声明：…'`。

词典格式
--------
XUnity 的 Text 词表是每行 `原文=译文`，换行必须写成字面量 `\\n`。
含 `=` 的原文会破坏格式，直接跳过。

一个容易踩的坑：XUnity 有 `MaxCharactersPerTranslation`（默认 200），
超过这个长度的原文**根本不会翻译**。本游戏有 155 条超长台词，必须调大
（本模块写到 2500，即插件上限）。

线程安全
--------
本模块不做网络请求，只读写本地文件，可以在任意线程调用。
"""
