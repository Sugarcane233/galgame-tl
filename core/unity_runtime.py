@dataclass
class RuntimeResult:
    ok: bool = False
    installed: list[str] = field(default_factory=list)   # 装了哪些组件
    dict_path: Optional[Path] = None
    entries: int = 0
    lines: int = 0
    launcher: Optional[str] = None      # 跑游戏要用的启动脚本
    notes: list[str] = field(default_factory=list)


# ---------------------------------------------------------------- 环境探测
def _is_mono(root: Path) -> bool:
    """Mono 版才有 Assembly-CSharp.dll；IL2CPP 版是 GameAssembly.so。

    BepInEx 5.x 只能跑 Mono 版。IL2CPP 需要 BepInEx 6（IL2CPP 构建）+ 
    XUnity 的 IL2CPP 包，本模块不做。
    """
    for sub in root.glob("*_Data"):
        if (sub / "Managed" / "Assembly-CSharp.dll").is_file():
            return True
    return False


def _game_dir(root: Path) -> Path:
    """找到含 `*_Data` 的那一层（玩家可能把游戏套了一层目录）。"""
    if any(root.glob("*_Data")):
        return root
    for sub in root.iterdir():
        if sub.is_dir() and any(sub.glob("*_Data")):
            return sub
    return root


def _uses_tmp(root: Path) -> bool:
    """游戏是否用了 TextMeshPro（决定要不要塞 29MB 的 TMP 中文字体包）。

    判据看 Assembly-CSharp.dll 里有没有引用 `TMPro` 命名空间。比扫场景可靠：
    场景里 TextMeshProUGUI 是 MonoBehaviour，没有 TypeTree 根本读不出类名。
    """
    for sub in root.glob("*_Data"):
        dll = sub / "Managed" / "Assembly-CSharp.dll"
        if not dll.is_file():
            continue
        try:
            # 只查前 8MB：字符串表在 PE 里靠前，读完整个 dll 没必要
            with open(dll, "rb") as f:
                blob = f.read(8 << 20)
        except OSError:
            return False
        return b"TMPro" in blob or b"TextMeshPro" in blob
    return False


def _executable(root: Path) -> Optional[Path]:
    """找游戏主程序（BepInEx 的 run_bepinex.sh 要它作参数）。

    有两个坑：
    1. 按大小排序会把我们自己塞进去的 TMP 字体包（29MB）当成主程序 ——
       实测启动脚本被写成 `executable_name="arialuni_sdf_u2019"`，
       BepInEx 直接把字体 bundle 当游戏跑。所以必须**排除已知的辅助文件名**。
    2. 无后缀文件里既有游戏本体也有 assets 目录外的东西，不能只看后缀。
    """
    skip = {
        "run_bepinex.sh", "changelog.txt", "doorstop_config.ini",
        "libdoorstop.so", ".doorstop_version",
        FONT_ASSET, "arialuni_sdf_u2018", "arialuni_sdf_u2019",
    }
    cands = []
    for f in root.iterdir():
        if not f.is_file() or f.name in skip:
            continue
        if f.name.startswith("."):
            continue
        name = f.name.lower()
        if name.endswith((".x86_64", ".x86", ".exe")):
            cands.append(f)
        elif f.suffix == "" and f.stat().st_size > 1 << 20:
            cands.append(f)
    # 带 .x86_64/.x86/.exe 后缀的优先，其次再比大小
    cands.sort(key=lambda p: (0 if p.name.lower().endswith((".x86_64", ".x86", ".exe")) else 1,
                              -p.stat().st_size))
    return cands[0] if cands else None


def _download(url: str, dst: Path, log: Callable[[str], None]) -> bool:
    """带代理与降级重试的下载。

    本机 FlClash 对 github 的 TLS1.3 握手会 `unexpected eof`，urllib 默认
    协商 TLS1.3 就会失败 —— 这里不控 TLS 版本（urllib 没有该开关），
    失败时提示用户用代理环境变量重跑。
    """
    log(f"下载 {url.rsplit('/', 1)[-1]} …")
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "galgame-tl"})
        with urllib.request.urlopen(req, timeout=120) as r, open(dst, "wb") as f:
            shutil.copyfileobj(r, f)
        return dst.stat().st_size > 1024
    except Exception as e:
        log(f"  下载失败：{e}")
        log("  提示：设置 HTTPS_PROXY=http://127.0.0.1:7890 后重试")
        return False


def _unzip(zip_path: Path, dest: Path) -> None:
    with zipfile.ZipFile(zip_path) as z:
        z.extractall(dest)


# ---------------------------------------------------------------- 安装
def install(root: Path, log: Callable[[str], None] = lambda s: None,
            cache_dir: Optional[Path] = None) -> RuntimeResult:
    """把 BepInEx + XUnity.AutoTranslator 装进游戏目录。

    幂等：已经装过的组件跳过。返回的 `launcher` 是以后启动游戏该用的脚本。
    """
    res = RuntimeResult()
    root = _game_dir(root)
    if not _is_mono(root):
        res.notes.append("不是 Mono 版（缺 Assembly-CSharp.dll），"
                         "BepInEx 5.x 装不上；IL2CPP 版需另走 BepInEx 6。")
        return res

    cache = cache_dir or Path(tempfile.gettempdir()) / "galgame-tl-rt"
    cache.mkdir(parents=True, exist_ok=True)

    # --- BepInEx ---
    core = root / "BepInEx" / "core"
    if (core / "BepInEx.Preloader.dll").is_file():
        log("BepInEx 已安装，跳过")
        res.installed.append("bepinex(cached)")
    else:
        z = cache / f"BepInEx_linux_{BEPINEX_VER}.zip"
        if not z.exists() and not _download(BEPINEX_URL, z, log):
            res.notes.append("BepInEx 下载失败")
            return res
        log("解压 BepInEx …")
        _unzip(z, root)
        res.installed.append("bepinex")

    # --- XUnity.AutoTranslator ---
    xdir = root / "BepInEx" / "plugins" / "XUnity.AutoTranslator"
    if (xdir / "XUnity.AutoTranslator.Plugin.BepInEx.dll").is_file():
        log("XUnity.AutoTranslator 已安装，跳过")
        res.installed.append("xunity(cached)")
    else:
        z = cache / f"XUnity.AutoTranslator-BepInEx-{XUAT_VER}.zip"
        if not z.exists() and not _download(XUAT_URL, z, log):
            res.notes.append("XUnity.AutoTranslator 下载失败")
            return res
        log("解压 XUnity.AutoTranslator …")
        _unzip(z, root)
        res.installed.append("xunity")

    # --- TextMeshPro 中文字体 ---
    #
    # TMP 游戏（Fungus + TMPro 常见）默认字体只有拉丁字形，换成中文后
    # 满屏方框。必须挂一份带 CJK 的 TMP font asset。
    #
    # 只对声明用了 TMP 的游戏装：纯 UGUI Text 的游戏用 OverrideFont
    # （系统字体名）就够了，塞 29MB 的 bundle 是浪费。
    if _uses_tmp(root):
        if (root / FONT_ASSET).is_file():
            log("TMP 中文字体已存在，跳过")
            res.installed.append("font(cached)")
        else:
            z = cache / f"TMP_Font_AssetBundles_{FONT_VER}.zip"
            if not z.exists() and not _download(FONT_URL, z, log):
                res.notes.append("字体包下载失败（中文会显示成方框，"
                                 "可手动解压 TMP_Font_AssetBundles.zip 到游戏目录）")
            else:
                log("解压 TMP 中文字体 …")
                _unzip(z, root)
                res.installed.append("font")
    else:
        res.notes.append("游戏没用 TextMeshPro，跳过中文字体包")

    # --- 启动脚本 ---
    runner = root / "run_bepinex.sh"
    exe = _executable(root)
    if runner.is_file() and exe:
        runner.chmod(0o755)
        txt = runner.read_text(encoding="utf-8", errors="replace")
        # 只在还是空模板时写入；用户改过就不动
        if re.search(r'^executable_name=""$', txt, re.M):
            txt = re.sub(r'^executable_name=""$',
                         f'executable_name="{exe.name}"', txt, count=1, flags=re.M)
            runner.write_text(txt, encoding="utf-8")
            log(f"启动脚本已指向 {exe.name}")
        res.launcher = "./run_bepinex.sh"
    res.ok = True
    return res


# ---------------------------------------------------------------- 配置
# 中文字体候选（系统字体，供 UGUI Text 的 OverrideFont 用）。
# 这些是 Linux 上常见的 CJK 字体族名，XUnity 会调
# `Font.CreateDynamicFontFromOSFont(name)` —— 名字必须和 fontconfig 里的
# family 完全一致，写错就静默不生效。
_CJK_FONTS = (
    "Noto Sans CJK SC",
    "Source Han Sans SC",
    "WenQuanYi Micro Hei",
    "Droid Sans Fallback",
    "AR PL UMing CN",
)


def _pick_system_cjk_font() -> str:
    """挑一个系统上真装了的 CJK 字体族名；没有就返回空串。"""
    try:
        import subprocess as sp
        out = sp.run(["fc-list", ":lang=zh", "family"], capture_output=True,
                     text=True, timeout=8).stdout
    except Exception:
        return ""
    have = {line.split(",")[0].strip() for line in out.splitlines() if line.strip()}
    for name in _CJK_FONTS:
        if name in have:
            return name
    return ""


def _font_values(root: Path) -> tuple[str, str]:
    """生成 ini 模板时该填的两个字体值：(OverrideFont, OverrideFontTextMeshPro)。

    TMP 游戏挂 asset bundle 名（`arialuni_sdf_u2018`）；纯 UGUI 游戏挂系统
    字体族名。两者互斥：给 UGUI 游戏填 TMP 的包名没用，反之亦然。
    """
    if _uses_tmp(root) and (root / FONT_ASSET).is_file():
        return "", FONT_ASSET
    return _pick_system_cjk_font(), ""


def configure(root: Path, lang: str = "zh-CN", from_lang: str = "en",
              log: Callable[[str], None] = lambda s: None) -> bool:
    """写 AutoTranslatorConfig.ini，配成「只用离线词表」。

    `Endpoint=` 留空 = 不配在线翻译器，XUnity 只查词典；查不到就保持原文
    （不会去连网、也不会把未翻译文本吐回屏幕）。

    ini 不存在时**直接按模板写一份**：它是 XUnity 首次启动才生成的，等用户
    先手动开一次游戏就把流水线卡死了（实测踩过）。
    """
    root = _game_dir(root)
    ini = root / "BepInEx" / "config" / "AutoTranslatorConfig.ini"
    fv = _font_values(root)
    if not ini.is_file():
        ini.parent.mkdir(parents=True, exist_ok=True)
        ini.write_text(
            INI_TEMPLATE.format(endpoint="", lang=lang, from_lang=from_lang,
                                max_chars=MAX_CHARS_PER_TRANSLATION,
                                font_ugui=fv[0], font_tmp=fv[1]),
            encoding="utf-8",
        )
        log(f"配置已生成：Language={lang} FromLanguage={from_lang} Endpoint=(空，纯离线)")
        return True

    txt = ini.read_text(encoding="utf-8", errors="replace")
    subs = {
        "Language": lang,
        "FromLanguage": from_lang,
        "Endpoint": "",
        "FallbackEndpoint": "",
        "MaxCharactersPerTranslation": str(MAX_CHARS_PER_TRANSLATION),
        # 打字机效果：游戏逐字 set_text（"H" / "He" / "Hel"…），词典只能命中
        # 完整句子，中间态全是英文，观感很差。开启后 XUnity 会为每个词典条目的
        # 所有前缀预生成译文，逐字显示时也是中文。
        "GeneratePartialTranslations": "True",
    }
    # 中文字体。TMP 游戏挂 asset bundle 名，纯 UGUI 游戏挂系统字体名。
    # UGUI 的 OverrideFont 吃系统字体名（会走 Font.CreateDynamicFontFromOSFont），
    # TMP 的 OverrideFontTextMeshPro 吃 asset bundle 文件名。
    if fv[1]:
        subs["OverrideFontTextMeshPro"] = fv[1]
        log(f"中文字体已挂：{fv[1]}")
    elif fv[0]:
        subs["OverrideFont"] = fv[0]
        log(f"中文字体已挂（系统字体）：{fv[0]}")
    for k, v in subs.items():
        pat = re.compile(rf"^{k}=.*$", re.M)
        if pat.search(txt):
            txt = pat.sub(lambda m, v=v: f"{k}={v}", txt, count=1)
        elif "[Service]" in txt:
            txt = txt.replace("[Service]", f"[Service]\n{k}={v}", 1)
    ini.write_text(txt, encoding="utf-8")
    log(f"配置已改：Language={lang} FromLanguage={from_lang} Endpoint=(空，纯离线)")
    return True


# ---------------------------------------------------------------- 词典
def _esc(s: str) -> str:
    """XUnity 词表是单行格式，换行必须写成字面量 `\\n`。"""
    return s.replace("\r\n", "\n").replace("\n", "\\n")


# 说话人前缀：行首的 `Name:`（冒号后紧跟非空白，才是前缀）。
#
# 判据必须是「冒号后紧跟非空白」：Fungus 把 `You:'What?'` 拼成一块，
# 而 UI 标签是 `Day: {$day}`、`Slot 2: Cheat to rank 3`（冒号后有空格）。
# 混用会让 UI 标签被当成说话人剥掉。
_SPEAKER_RX = re.compile(r"^([A-Za-z][A-Za-z0-9_ ]{0,14}):(?=\S)(?![/\\])")
# 译文侧的对应形态：`你:“什么？”`。中文名 1-4 字 + 半/全角冒号。
_ZH_SPEAKER_RX = re.compile(r"^([\u4e00-\u9fff]{1,4})\s*[:：](?=[^\s])")
# 只剩说话人名、没有台词的空壳（`Her:` / `你：`），剥标记后产生
_EMPTY_SPEAKER_RX = re.compile(r"^(?:[A-Za-z][A-Za-z0-9_ ]{0,14}|[\u4e00-\u9fff]{1,4})\s*[:：]\s*$")


# Fungus / TextMeshPro 的运行时标记。这些在 Writer 里是独立 token，
# 由 ProcessTokens 的 switch 分支处理，**不会进入 Text 组件的文本**：
#
#   {w=1}   停 1 秒        {x}   等玩家点击
#   {wc}    清屏           {c}   清屏
#   {s=100} 打字速度        {punch}/{vpunch}/{hpunch}/{flash}  特效
#   {audio=..} 配音         {m=..}/{exit}
#
# 而游戏读到的是「去掉标记后的纯文字」，所以词表 key 也必须去掉它们，
# 否则永远匹配不上。
#
# 注意 `{$var}` 是变量插值，**会**进入文本（替换成具体值），不能删。
_FUNGUS_CMD = re.compile(
    r"\{(?:x|wc|c|exit|w=[\d.]+|s=[\d.]+|speed=[\d.]+|m=[^}]*|"
    r"vpunch=[^}]*|hpunch=[^}]*|punch=[^}]*|flash=[^}]*|audio[^}]*)\}",
    re.I)


def _strip_cmds(s: str) -> str:
    """去掉 Fungus 运行时标记（不删 `{$var}` 变量插值）。"""
    return _FUNGUS_CMD.sub("", s)


def _sanitize_key(k: str) -> str:
    """把原文压成 XUnity 词表能吃的 key。

    XUnity 的词典是 `原文=译文` 的单行格式，解析时按第一个 `=` 切分，
    所以**原文里不能有 `=`**。之前的实现遇到含 `=` 的 key 直接 `continue`
    整条丢弃 —— 而 Fungus 的 `{w=1}` 就带等号，实测 114 条对话（大多是
    呻吟喘息块）因此全部没进词表，玩家看到的就是英文。

    正确做法是先把运行时标记去掉，再折叠多余空白。
    """
    s = _strip_cmds(k)
    s = s.replace("\r\n", "\n")
    # 逐行清理：标记被删后原来夹在标记之间的空格会留在行尾
    # （`'It...hurts...'{w=1} {x}\n\n` → `'It...hurts...' \n\n`），
    # 而 Fungus 实际塞进 Text 的是不带这些空格的版本。
    out_lines: list[str] = []
    blank = False
    for line in s.split("\n"):
        line = re.sub(r"[ \t]{2,}", " ", line).strip()
        if not line:
            if out_lines and not blank:
                out_lines.append("")
                blank = True
            continue
        out_lines.append(line)
        blank = False
    while out_lines and out_lines[-1] == "":
        out_lines.pop()
    s = "\n".join(out_lines)
    if "=" in s:
        return ""
    return s


def build_dictionary(cache: dict[str, str], out_dir: Path,
                     log: Callable[[str], None] = lambda s: None) -> tuple[int, int]:
    """把翻译缓存转成 XUnity 词表，返回 (完整条目数, 单行条目数)。

    为什么要三份
    ------------
    Unity 里一个 Text 组件的字符串可能包含多行
    （`Her:'...'\n\nYou:'...'`），也可能被游戏拆成单行分别塞进不同组件。
    全交给 XUnity 去猜不可靠，所以三套都写：

      * `galgame-tl-full.txt`  —— 整条匹配（`You:'What?'`）；
      * `galgame-tl-lines.txt` —— 按行拆开（`You:'What?'` / `'...'`）；
      * `galgame-tl-nospeaker.txt` —— **去掉说话人前缀**（`'What?'`）。

    第三份是打字机效果的关键。Fungus 的 SayDialog 把「说话人名」和「台词」
    分给两个不同的 Text 组件：屏幕上是「你」在一个框里、`'What?'` 在另一个框里。
    词典里只存 `You:'What?'` 就永远匹配不上单独的 `'What?'`，于是逐字显示时
    全是英文。所以拆行之后还要把行首的 `Name:` 剥掉再存一份。

    另一个关键：XUnity 的 partial translations 机制会为每个 key 的**所有前缀**
    预生成译文，所以逐字显示时也能是中文 —— 前提是 key 本身是「游戏真正
    塞进 Text 的那串字符」。带 `{w=1}` 这类标记的 key 匹配不上，等于白存。

    XUnity 会读 Text 目录下所有 .txt，重复的以后加载的为准，所以文件名
    用 `galgame-tl-` 前缀，避免和它自己生成的 `_AutoGeneratedTranslations`
    打架。加载顺序按文件名字母序：full < lines < nospeaker，所以 nospeaker
    优先级最高 —— 这正是我们要的（越短越泛用，能被更多组件命中）。
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    full: dict[str, str] = {}
    lines: dict[str, str] = {}
    nospeaker: dict[str, str] = {}
    n_bad_key = n_line_mismatch = 0

    for k, v in cache.items():
        if not v or not v.strip():
            continue
        k2 = _sanitize_key(k)
        v2 = _sanitize_key(v)
        if not k2 or not v2:
            if _strip_cmds(k).strip():
                n_bad_key += 1
            continue
        full.setdefault(k2, v2)

        ks = [x.strip() for x in k2.split("\n")]
        vs = [x.strip() for x in v2.split("\n")]
        # 行数不等不能整条丢：模型经常把两句合成一句、或把一句拆成两句，
        # 尤其带 `{w=1}` 的段落。整条丢弃会让这些台词永远不翻。
        # 这里退化成「按行内容逐句配对」，配不上的部分只进 full。
        if len(ks) == len(vs):
            pairs = list(zip(ks, vs))
        else:
            n_line_mismatch += 1
            pairs = list(zip(ks, vs)) if len(ks) <= len(vs) else \
                list(zip(ks, vs + [""] * (len(ks) - len(vs))))

        for a, b in pairs:
            a, b = a.strip(), b.strip()
            if not a or not b or "=" in a:
                continue
            # 标记被剥掉后可能只剩个说话人名（`Her:`），这种 key 没有意义，
            # 而且 `Her:=Her:` 会让 XUnity 把任何 `Her:` 都替换成 `Her:`。
            if a == b or _EMPTY_SPEAKER_RX.match(a):
                continue
            lines.setdefault(a, b)
            # 剥说话人前缀：原文 `You:'What?'` → `'What?'`。
            # 译文侧两种形态都要处理：说话人名可能被模型保留成英文
            # （`You:“什么？”`，因为 PROTECT_RULES 把前缀保护起来了），
            # 也可能被译成中文（`你:“什么？”`）。
            a2 = _SPEAKER_RX.sub("", a, count=1).strip()
            b2 = _SPEAKER_RX.sub("", b, count=1)
            b2 = _ZH_SPEAKER_RX.sub("", b2, count=1).strip()
            if a2 and b2 and a2 != a:
                nospeaker.setdefault(a2, b2)

    files = (
        ("galgame-tl-full.txt", full),
        ("galgame-tl-lines.txt", lines),
        ("galgame-tl-nospeaker.txt", nospeaker),
    )
    for name, d in files:
        p = out_dir / name
        with open(p, "w", encoding="utf-8") as f:
            f.write("# galgame-tl 离线词表（XUnity.AutoTranslator）\n")
            f.write("# 格式：原文=译文；换行写作 \\n\n")
            for k, v in sorted(d.items()):
                f.write(f"{_esc(k)}={_esc(v)}\n")
    extra = ""
    if n_line_mismatch:
        extra += f"（{n_line_mismatch} 条译文行数与原文不同，已按句尽量配对）"
    if n_bad_key:
        extra += f"（{n_bad_key} 条原文含等号且无法清理，跳过）"
    log(f"词表已写：完整 {len(full)} 条 / 单行 {len(lines)} 条 / "
        f"去说话人 {len(nospeaker)} 条 → {out_dir}{extra}")
    return len(full), len(lines)


def apply_runtime(root: Path, cache: dict[str, str], lang: str = "zh-CN",
                  from_lang: str = "en",
                  log: Callable[[str], None] = lambda s: None) -> RuntimeResult:
    """一步到位：装 BepInEx+XUnity → 改配置 → 写词表。

    调用方之后只需提示用户「用 run_bepinex.sh 启动游戏」。
    """
    res = install(root, log)
    if not res.ok:
        return res
    root = _game_dir(root)
    if not configure(root, lang, from_lang, log):
        res.notes.append("配置失败：先手动跑一次游戏生成 ini")
        res.ok = False
        return res
    tdir = root / "BepInEx" / "Translation" / lang / "Text"
    res.entries, res.lines = build_dictionary(cache, tdir, log)
    res.dict_path = tdir
    return res


# ---------------------------------------------------------------- 校验
def verify(root: Path, log: Callable[[str], None] = lambda s: None) -> dict:
    """启动游戏一次并检查日志：不该有 serialization 警告或 corrupted。"""
    root = _game_dir(root)
    runner = root / "run_bepinex.sh"
    if not runner.is_file():
        return {"ok": False, "error": "没装 BepInEx"}
    logf = Path(tempfile.gettempdir()) / "galgame-tl-verify.log"
    try:
        subprocess.run(["timeout", "45", "./run_bepinex.sh", "-logFile", str(logf)],
                       cwd=root, capture_output=True, timeout=60)
    except Exception as e:
        return {"ok": False, "error": str(e)}
    text = logf.read_text(encoding="utf-8", errors="replace") if logf.exists() else ""
    out = {
        "ok": True,
        "layout_warnings": text.count("serialization layout"),
        "corrupted": text.count("corrupted"),
        "translated": text.count("Setting text on"),
        "xunity_loaded": "Loaded XUnity.AutoTranslator into Unity" in text,
        "log": str(logf),
    }
    if out["layout_warnings"] or out["corrupted"]:
        out["ok"] = False
    log(f"校验：layout 警告 {out['layout_warnings']} / corrupted {out['corrupted']} "
        f"/ 替换 {out['translated']} 处")
    return out
